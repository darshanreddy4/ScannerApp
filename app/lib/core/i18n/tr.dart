import 'app_language.dart';
import 'translations.dart';

/// The language the text is shown in, readable from anywhere. The settings screen updates it when another language is chosen.
abstract final class Strings {
  static String code = 'en';

  static bool get isEnglish => code == 'en';

  static void use(AppLanguage language) => code = language.resolved;
}

/// The text in the chosen language. Text that has no translation stays in English.
String tr(String english) {
  if (Strings.isEnglish) return english;
  return translations[Strings.code]?[english] ?? english;
}

/// [tr] for text with parts: "{n} pages" with {'n': 3}. The translation keeps the same {names}.
String trf(String template, Map<String, Object> values) {
  var out = tr(template);
  values.forEach((k, v) => out = out.replaceAll('{$k}', '$v'));
  return out;
}

